-- LessFun — encrypted private messages.
--
-- Run this once in the Supabase SQL editor after admins_avatars.sql:
--   Project -> SQL Editor -> New query -> paste -> Run
--
-- Security model
-- --------------
-- Messages are encrypted in the browser with ECDH (P-256) + AES-GCM before
-- they reach Supabase. The database stores only ciphertext, an IV, sender, and
-- recipient. Private keys stay in the browser's localStorage; public keys are
-- published in users.public_key.
--
-- This protects message contents from the database and casual operators, but
-- it is not a replacement for Supabase Auth: account sign-in is still handled
-- by the beta's public.users table, so treat this as strong transport/content
-- encryption rather than a hardened production messenger.

alter table if exists public.users
    add column if not exists public_key text not null default '';

create table if not exists public.direct_messages (
    id         bigint generated by default as identity primary key,
    sender     text        not null,
    recipient  text        not null,
    ciphertext text        not null,
    iv         text        not null,
    created_at timestamptz not null default now()
);

create index if not exists lessfun_direct_messages_sender_idx
    on public.direct_messages (sender, created_at desc);
create index if not exists lessfun_direct_messages_recipient_idx
    on public.direct_messages (recipient, created_at desc);

alter table public.direct_messages enable row level security;

drop policy if exists "lessfun_direct_messages_read" on public.direct_messages;
create policy "lessfun_direct_messages_read"
    on public.direct_messages for select
    using (true);

drop policy if exists "lessfun_direct_messages_insert" on public.direct_messages;
create policy "lessfun_direct_messages_insert"
    on public.direct_messages for insert
    with check (true);

drop policy if exists "lessfun_direct_messages_delete" on public.direct_messages;
create policy "lessfun_direct_messages_delete"
    on public.direct_messages for delete
    using (true);

grant select, insert, delete on public.direct_messages to anon, authenticated;

-- Users need to publish and read public keys.
alter table if exists public.users enable row level security;

drop policy if exists "lessfun_users_update" on public.users;
create policy "lessfun_users_update"
    on public.users for update
    using (true)
    with check (true);

grant select, insert, update, delete on public.users to anon, authenticated;
