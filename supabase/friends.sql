-- LessFun — friends, requests, and presence.
--
-- Run this once in the Supabase dashboard:
--   Project -> SQL Editor -> New query -> paste -> Run
--
-- ⚠️  Like the rest of this developer beta, the client uses the publishable
-- key with no server-side auth. These policies are intentionally open so the
-- static site can work without a backend. Move to Supabase Auth and
-- auth.uid()-based policies before handling real user data.

create table if not exists public.friendships (
    id         bigint generated by default as identity primary key,
    requester  text        not null,
    recipient  text        not null,
    status     text        not null default 'pending'
                            check (status in ('pending', 'accepted')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (requester, recipient),
    check (requester <> recipient)
);

create index if not exists lessfun_friendships_requester_idx
    on public.friendships (requester, status);
create index if not exists lessfun_friendships_recipient_idx
    on public.friendships (recipient, status);

alter table public.friendships enable row level security;

drop policy if exists "lessfun_friendships_read" on public.friendships;
create policy "lessfun_friendships_read"
    on public.friendships for select
    using (true);

drop policy if exists "lessfun_friendships_insert" on public.friendships;
create policy "lessfun_friendships_insert"
    on public.friendships for insert
    with check (true);

drop policy if exists "lessfun_friendships_update" on public.friendships;
create policy "lessfun_friendships_update"
    on public.friendships for update
    using (true)
    with check (true);

drop policy if exists "lessfun_friendships_delete" on public.friendships;
create policy "lessfun_friendships_delete"
    on public.friendships for delete
    using (true);

grant select, insert, update, delete on public.friendships to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- Presence / last seen. Online means last_seen within ~90 seconds.
create table if not exists public.user_presence (
    username  text primary key,
    last_seen timestamptz not null default now()
);

create index if not exists lessfun_user_presence_seen_idx
