-- LessFun — Shells wallet, cosmetics inventory, and score persistence.
--
-- Run this once in the Supabase dashboard:
--   Project -> SQL Editor -> New query -> paste -> Run
--
-- ⚠️  Security note
-- LessFun currently signs users in against the public.users table with the
-- publishable (anon) key instead of Supabase Auth. That means the policies
-- below have to be permissive for the game to work without a server. They are
-- fine for a developer beta with no real-money purchases. Before selling
-- anything, move accounts to Supabase Auth and replace the policies with
-- auth.uid()-based rules.

-- ---------------------------------------------------------------------------
-- Users (allows account creation from the browser)
-- ---------------------------------------------------------------------------
alter table if exists public.users enable row level security;

drop policy if exists "lessfun_users_read" on public.users;
create policy "lessfun_users_read"
    on public.users for select
    using (true);

drop policy if exists "lessfun_users_insert" on public.users;
create policy "lessfun_users_insert"
    on public.users for insert
    with check (true);

-- Owner-only delete is enforced in the UI (TotallyMason + password unlock).
-- The database policy is intentionally open because this beta has no
-- server-side owner role yet.
drop policy if exists "lessfun_users_delete" on public.users;
create policy "lessfun_users_delete"
    on public.users for delete
    using (true);

grant select, insert, delete on public.users to anon, authenticated;

-- ---------------------------------------------------------------------------
-- Shells wallets
-- ---------------------------------------------------------------------------
create table if not exists public.wallets (
    username       text primary key,
    shells         integer     not null default 100 check (shells >= 0),
    inventory      jsonb       not null default '["paint_coral", "board_teal"]'::jsonb,
    equipped       jsonb       not null default '{"paint": "paint_coral", "board": "board_teal"}'::jsonb,
    streak         integer     not null default 0 check (streak >= 0),
    last_play_day  date,
    streak_rewards jsonb       not null default '[]'::jsonb,
    total_earned   integer     not null default 0 check (total_earned >= 0),
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now()
);

alter table public.wallets enable row level security;

drop policy if exists "lessfun_wallets_read" on public.wallets;
create policy "lessfun_wallets_read"
    on public.wallets for select
    using (true);

drop policy if exists "lessfun_wallets_insert" on public.wallets;
create policy "lessfun_wallets_insert"
    on public.wallets for insert
    with check (true);

drop policy if exists "lessfun_wallets_update" on public.wallets;
create policy "lessfun_wallets_update"
    on public.wallets for update
    using (true)
    with check (true);

-- Used when the owner deletes an account from the debug tab.
drop policy if exists "lessfun_wallets_delete" on public.wallets;
create policy "lessfun_wallets_delete"
    on public.wallets for delete
    using (true);

grant select, insert, update, delete on public.wallets to anon, authenticated;

-- ---------------------------------------------------------------------------
-- Scores (the app already tries to write here)
-- ---------------------------------------------------------------------------
create table if not exists public.scores (
    id         bigint generated by default as identity primary key,
    username   text        not null,
    game       text        not null,
    score      integer     not null default 0 check (score >= 0),
    created_at timestamptz not null default now()
);

create index if not exists lessfun_scores_game_score_idx
    on public.scores (game, score desc);

alter table public.scores enable row level security;

drop policy if exists "lessfun_scores_read" on public.scores;
create policy "lessfun_scores_read"
    on public.scores for select
    using (true);

drop policy if exists "lessfun_scores_insert" on public.scores;
create policy "lessfun_scores_insert"
    on public.scores for insert
    with check (true);

grant select, insert on public.scores to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

