-- LessFun — developer console and owner approval queue.
--
-- Run once in the Supabase SQL editor after messages.sql and owner_tools.sql.
--
-- Appointed developers write change requests in the in-game Developer Console.
-- Every request is stored with a pending status and is only marked approved by
-- the owner (TotallyMason). The owner sees the full activity feed.

alter table if exists public.users
    add column if not exists developer boolean not null default false;

create table if not exists public.developer_requests (
    id          bigint generated by default as identity primary key,
    developer   text        not null,
    message     text        not null,
    status      text        not null default 'pending',
    owner_note  text        not null default '',
    reviewed_by text        not null default '',
    reviewed_at timestamptz,
    created_at  timestamptz not null default now()
);

create index if not exists lessfun_developer_requests_developer_idx
    on public.developer_requests (developer, created_at desc);
create index if not exists lessfun_developer_requests_status_idx
    on public.developer_requests (status, created_at desc);

alter table public.developer_requests enable row level security;

drop policy if exists "lessfun_developer_requests_read" on public.developer_requests;
create policy "lessfun_developer_requests_read"
    on public.developer_requests for select
    using (true);

drop policy if exists "lessfun_developer_requests_insert" on public.developer_requests;
create policy "lessfun_developer_requests_insert"
    on public.developer_requests for insert
    with check (true);

drop policy if exists "lessfun_developer_requests_update" on public.developer_requests;
create policy "lessfun_developer_requests_update"
    on public.developer_requests for update
    using (true)
    with check (true);

drop policy if exists "lessfun_developer_requests_delete" on public.developer_requests;
create policy "lessfun_developer_requests_delete"
    on public.developer_requests for delete
    using (true);

grant select, insert, update, delete on public.developer_requests to anon, authenticated;

-- The owner console needs to appoint or remove developers.
alter table if exists public.users enable row level security;

drop policy if exists "lessfun_users_update" on public.users;
create policy "lessfun_users_update"
    on public.users for update
    using (true)
    with check (true);

grant select, insert, update, delete on public.users to anon, authenticated;
