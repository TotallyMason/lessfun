-- LessFun — coin gift notifications.
--
-- Run this once in the Supabase SQL editor:
--   Project -> SQL Editor -> New query -> paste -> Run
--
-- Records each Coin gift so the recipient sees who sent it and how much.
-- Notifications are shown in the bell menu in the top bar.

create table if not exists public.coin_gifts (
    id         bigint generated by default as identity primary key,
    sender     text        not null,
    recipient  text        not null,
    amount     integer     not null check (amount > 0),
    seen       boolean     not null default false,
    created_at timestamptz not null default now()
);

create index if not exists lessfun_coin_gifts_recipient_idx
    on public.coin_gifts (recipient, created_at desc);

alter table public.coin_gifts enable row level security;

drop policy if exists "lessfun_coin_gifts_read" on public.coin_gifts;
create policy "lessfun_coin_gifts_read"
    on public.coin_gifts for select
    using (true);

drop policy if exists "lessfun_coin_gifts_insert" on public.coin_gifts;
create policy "lessfun_coin_gifts_insert"
    on public.coin_gifts for insert
    with check (true);

drop policy if exists "lessfun_coin_gifts_update" on public.coin_gifts;
create policy "lessfun_coin_gifts_update"
    on public.coin_gifts for update
    using (true)
    with check (true);

grant select, insert, update on public.coin_gifts to anon, authenticated;
