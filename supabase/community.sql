-- LessFun — community replies, reactions, uploads, and extra owner toggles.
--
-- Run this once in the Supabase dashboard:
--   Project -> SQL Editor -> New query -> paste -> Run
--
-- Adds:
--   * post attachments stored as inline data URLs (small files only)
--   * replies to posts
--   * reactions for posts and replies
--   * new site-wide switches used by the Owner Console

alter table if exists public.posts add column if not exists media_url  text;
alter table if exists public.posts add column if not exists media_name text;
alter table if exists public.posts add column if not exists media_type text;
alter table if exists public.posts add column if not exists media_size integer not null default 0;

alter table if exists public.posts enable row level security;

drop policy if exists "lessfun_posts_read" on public.posts;
create policy "lessfun_posts_read"
    on public.posts for select
    using (true);

drop policy if exists "lessfun_posts_insert" on public.posts;
create policy "lessfun_posts_insert"
    on public.posts for insert
    with check (true);

drop policy if exists "lessfun_posts_update" on public.posts;
create policy "lessfun_posts_update"
    on public.posts for update
    using (true)
    with check (true);

drop policy if exists "lessfun_posts_delete" on public.posts;
create policy "lessfun_posts_delete"
    on public.posts for delete
    using (true);

grant select, insert, update, delete on public.posts to anon, authenticated;

-- ---------------------------------------------------------------------------
-- Replies
-- ---------------------------------------------------------------------------
create table if not exists public.post_replies (
    id         bigint generated by default as identity primary key,
    post_id    bigint      not null references public.posts(id) on delete cascade,
    username   text        not null,
    content    text        not null,
    created_at timestamptz not null default now()
);

create index if not exists lessfun_post_replies_post_idx
    on public.post_replies (post_id, created_at);

alter table public.post_replies enable row level security;

drop policy if exists "lessfun_post_replies_read" on public.post_replies;
